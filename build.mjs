// Builds a single self-contained HTML file (game/tallow-reach.html).
// Usage: node build.mjs            one-off build
//        node build.mjs --watch    rebuild on every save
import * as esbuild from "esbuild";
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { join } from "node:path";

const watch = process.argv.includes("--watch");
const shell = readFileSync("src/index.html", "utf8");
const css = readFileSync("src/styles.css", "utf8");

// `.glb` files dropped into src/assets/models/ replace the built-in models (see
// docs/GLB_MODELS.md). The manifest is regenerated on every build from whatever is
// there — an empty folder yields an empty manifest and changes nothing.
const MODELS_DIR = join("src", "assets", "models");
function generateModelManifest() {
  let files = [];
  try {
    files = readdirSync(MODELS_DIR).filter(f => f.toLowerCase().endsWith(".glb")).sort();
  } catch { /* no folder yet: no models */ }
  const lines = [
    "// AUTO-GENERATED by build.mjs — do not edit by hand.",
    "// It maps each .glb in src/assets/models/ to its bundled (data URL) source.",
    "// Drop a `<key>.glb` into src/assets/models/ and rebuild; this file is rewritten.",
  ];
  files.forEach((f, i) => lines.push(`import m${i} from "../assets/models/${f}";`));
  const entries = files.map((f, i) => `  ${JSON.stringify(f.replace(/\.glb$/i, ""))}: m${i},`);
  lines.push(entries.length ? `export default {\n${entries.join("\n")}\n};` : "export default {};");
  writeFileSync("src/render/model-manifest.js", lines.join("\n") + "\n");
}
generateModelManifest();

function writeBundle(result) {
  if (result.errors.length) {
    console.error("build failed");
    return;
  }
  const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
  const html = shell.replace("/*__CSS__*/", () => css).replace("/*__JS__*/", () => js);
  mkdirSync("game", { recursive: true });
  writeFileSync("game/tallow-reach.html", html);
  console.log(`built game/tallow-reach.html (${(html.length / 1024).toFixed(0)} KB)`);
}

const options = {
  entryPoints: ["src/main.js"],
  bundle: true,
  format: "iife",
  minify: true,
  target: "es2020",
  legalComments: "none",
  write: false,
  // Artwork (e.g. the slice-14c sky panorama) is inlined as base64 data URLs, so the build stays
  // one self-contained file and no asset path ever needs to resolve inside the sandbox.
  loader: { ".webp": "dataurl", ".glb": "dataurl" },
  plugins: [
    {
      name: "html-shell",
      setup(build) {
        build.onEnd(writeBundle);
      },
    },
  ],
};

if (watch) {
  const ctx = await esbuild.context(options);
  await ctx.watch();
  console.log("watching src/ ...");
} else {
  await esbuild.build(options); // the html-shell plugin writes the file
}
