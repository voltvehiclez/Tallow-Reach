// GLB model support: every object in the game can be drawn from a .glb instead of
// its built-in geometry. Drop `<key>.glb` into `src/assets/models/`, rebuild
// (`npm run build` regenerates `model-manifest.js` from whatever files are there) and the
// key's built-in model is replaced — no .glb for a key, nothing changes.
//
// Runtime contract:
//   - The title paints first; `preloadAfterPaint()` then loads models in the
//     background. Open World waits for readiness before gameplay. A broken file
//     logs and that key simply keeps its built-in look.
//   - `instantiateModel(key)` returns a fresh clone (geometry and materials shared)
//     or null when no .glb is registered for the key — callers fall back to their
//     built-in model.
//   - Node names are conventions, not code paths:
//       spin     rotates around Y at 0.1 rad/s (the station's ring behaviour)
//       eng      engine glow box — its z scale is driven by throttle/boost
//       noclip   contributes no collision triangles (glow shells, decoration)

import { LoadingManager } from "three";
import { DRACOLoader } from "three/examples/jsm/loaders/DRACOLoader.js";
import dracoSource from "../assets/decoders/draco-decoder.txt";
import { GLTFLoader } from "three/examples/jsm/loaders/GLTFLoader.js";
// Generated by build.mjs from whatever .glb files live in src/assets/models/;
// committed as an empty map so a fresh checkout builds before the first model lands.
import MODEL_URLS from "./model-manifest.js";

const templates = new Map();
const failures = [];
let preloadPromise = null;

const bufferOf = async source =>
  typeof source === "string" ? (await (await fetch(source)).arrayBuffer()) : source;

export function preloadModels(urls = MODEL_URLS) {
  if (preloadPromise) return preloadPromise;
  preloadPromise = (async () => {
    // Use the decoder already shipped with three.js, embedded as text. No CDN,
    // fetchable sidecar, or new dependency: even file:// builds stay standalone.
    const decoderURL = `data:text/javascript;charset=utf-8,${encodeURIComponent(dracoSource)}`;
    const manager = new LoadingManager();
    manager.setURLModifier(url => url === "draco_decoder.js" ? decoderURL : url);
    const draco = new DRACOLoader(manager).setDecoderConfig({ type: "js" }).setWorkerLimit(1);
    const parser = new GLTFLoader().setDRACOLoader(draco);
    try {
      await Promise.all(
        Object.entries(urls).map(async ([key, source]) => {
          try {
            const buffer = await bufferOf(source);
            const template = await new Promise((resolve, reject) => {
              parser.parse(buffer, "", gltf => resolve(gltf.scene), err => reject(err || new Error("parse failed")));
            });
            templates.set(key, template);
          } catch (err) {
            // A broken model must never break the build of the world: warn and fall back.
            console.warn(`[models] "${key}" failed to load; using the built-in model.`, err);
            failures.push(key);
          }
        })
      );
    } finally {
      draco.dispose();
      if (draco.workerSourceURL) URL.revokeObjectURL(draco.workerSourceURL);
    }
    return { loaded: [...templates.keys()], failed: failures };
  })();
  return preloadPromise;
}

/** The loaded template for `key`, or null (no .glb, or it failed). Callers clone. */
export function modelTemplate(key) {
  return templates.get(key) || null;
}

/** A fresh clone of the .glb registered as `key`, or null — the caller falls back to its built-in model. */
export function instantiateModel(key) {
  const template = templates.get(key);
  return template ? template.clone(true) : null;
}

/** Every node in `root` whose (case-insensitive) name matches `re`, depth-first. */
export function namedNodes(root, re) {
  const out = [];
  root?.traverse(node => {
    if (re.test(String(node?.name || ""))) out.push(node);
  });
  return out;
}

/** Nodes named `spin` (or `spin-*`) — what the model wants rotated, and at what rate it asked. */
export const spinNodes = root => namedNodes(root, /^spin([-_.].*)?$/i);
/**
 * Nodes named `eng` — the engine glow boxes the thrust throttle scales. Each node's authored
 * Z scale is remembered on `userData.engZ0` so the view can stretch the glow from whatever
 * length the model was authored at (the built-in boxes are 1).
 */
export const engNodes = root => {
  const nodes = namedNodes(root, /^eng([-_.].*)?$/i);
  for (const n of nodes) if (n.userData) n.userData.engZ0 = n.scale.z;
  return nodes;
};

/** Test/diagnostic hooks. */
export const loadedModelKeys = () => [...templates.keys()];
export const failedModelKeys = () => [...failures];

/** Give the title a paint opportunity before decoding any embedded models.
 * Two animation callbacks are intentional: work in the first callback still
 * runs BEFORE that frame is painted. Injectable dependencies keep this testable.
 */
export function preloadAfterPaint(schedule = requestAnimationFrame, load = preloadModels) {
  return new Promise(resolve => schedule(() => schedule(resolve))).then(() => load());
}
