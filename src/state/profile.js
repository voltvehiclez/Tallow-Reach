const HOME_STATION_KEY = stationKeyAt(DEFAULT_PLACE) || `${DEFAULT_PLACE}:station`;

/** Keep the old enumerable world.store API as an alias for Meridian while the
 * canonical runtime/save collection is keyed by station identity. */
function worldWithStationStores(fields, stationStores) {
  const stores = stationStores && typeof stationStores === "object" && !Array.isArray(stationStores)
    ? stationStores
    : {};
  if (!stores[HOME_STATION_KEY] || typeof stores[HOME_STATION_KEY] !== "object" || Array.isArray(stores[HOME_STATION_KEY])) {
    stores[HOME_STATION_KEY] = newStock();
  }
  const world = { ...fields, stationStores: stores };
  Object.defineProperty(world, "store", {
    enumerable: true,
    configurable: true,
    get: () => stores[HOME_STATION_KEY],
    set: value => { stores[HOME_STATION_KEY] = value && typeof value === "object" && !Array.isArray(value) ? value : newStock(); },
  });
  return world;
}

// Version history:
//   1  original prototype (no "v" field)
//   2  adds "v"; otherwise identical shape
//   3  adds "loadout": the modules fitted to each hull, bay by bay
//   4  adds "modules": the parts held in storage, ready to be fitted
//   5  basic thrusters become standard issue (auto-filled for < v5)
//   6  basic shields become standard issue (auto-filled for < v6)
//   7  basic cannons become standard issue in primary bay 0 (auto-filled for < v7)
//   8  mining beam becomes module `beam_basic` (wp.beam -> stored `beam_basic`)
//   9  missile launcher becomes module `missile_basic` (wp.msl -> stored `missile_basic`)
//   10 hull becomes module `hull_basic` (auto-filled for < v10)
//   11 per-ship holds `holds[shipId] = { cargo, modules }`
//   12 item catalogue (`data/items.js`): every place is `{ itemId: count }`
//   13 save split into portable `profile` and per-world `world` (`{ v: 13, profile, world }`);
//      `sanitizeWorld` walks `BASE_MODULES` rather than naming base modules by hand.
//   14 world.sector becomes world.place (a pocket id from data/places.js); v13 and
//      older sector ids migrate where valid, otherwise the starting pocket.
//   15 adds `world.resume`: null while docked, otherwise the exact spot the local
//      pilot was flying at (`pos`, `quat`) with their shield/boost levels. v14 and
//      older saves have none, so they keep the old behaviour (dock if the pocket
//      has a station, else fly in at the arrival point).
//   16 adds the starmap: world.galaxy stores only its seed and compact per-system
//      discovery/visit knowledge. Geography is regenerated by sim/galaxy-session.js.
//   17 saves the local route destination in world.destination; older saves default to none.
//   18 adds world.placeMemory: remaining simulation-time cooldowns for mined rocks
//      and cleared encounters. v17 and older start with an empty memory record.
//   18 also accepts station-local inventory records in world.stationStores;
//      older v18 saves migrate their legacy world.store to the relevant station.
//   19 replaces the single profile.mission slot with profile.missions and adds
//      remembered flags; v18 and older active contracts migrate into the runner's
//      one-step mission shape.
export const SAVE_VERSION = 19;

// A saved contract with a type not listed here is dropped on load, so this
// follows the contract definitions instead of keeping its own copy.
export const MISSION_TYPES = CONTRACT_TYPES;

/**
 * The modules hull `shipId` is delivered with: one entry per bay, `null` where
 * the bay is empty. Bay counts come from the hull's layout.
 */
export function stockFor(shipId) {
  const layout = layoutFor(shipId);
  const fit = {};
  for (const [g, slots] of Object.entries(layout)) {
    const list = Array.from({ length: slots }, () => null);
    (STOCK_FIT[g] || []).slice(0, slots).forEach((mod, i) => (list[i] = mod));
    fit[g] = list;
  }
  return fit;
}

/** An empty hold: nothing carried. One per owned ship (`profile.holds`). */
export const newHold = () => newStock();

/** A stock fit for every hull the game knows. */
function allStockFit() {
  const out = {};
  for (const id of Object.keys(SHIPS)) out[id] = stockFor(id);
  return out;
}

/**
 * A hull that is new to the fleet: its own empty hold, no remembered damage and
 * its stock modules fitted. EVERY way a ship can join the fleet goes through
 * here (buying one, or the station lending a replacement after a loss). A hull
 * is not just an id: without `loadout[ship]` it has no bays at all, so it can be
 * neither fitted in Outfitting nor flown (no thrusters, no Hull HP).
 */
export function addShipRecords(profile, id) {
  if (!profile || !SHIPS[id]) return profile;
  if (!profile.holds || typeof profile.holds !== "object") profile.holds = {};
  if (!profile.hp || typeof profile.hp !== "object") profile.hp = {};
  if (!profile.loadout || typeof profile.loadout !== "object") profile.loadout = {};
  profile.holds[id] = newHold();
  profile.hp[id] = 1;           // a fresh hull has no damage to remember
  profile.loadout[id] = stockFor(id);
  return profile;
}

/** Fill in only what hull `id` is missing, leaving anything it already has. */
export function ensureShipRecords(profile, id) {
  if (!profile || !SHIPS[id]) return profile;
  if (!profile.holds || typeof profile.holds !== "object") profile.holds = {};
  if (!profile.hp || typeof profile.hp !== "object") profile.hp = {};
  if (!profile.loadout || typeof profile.loadout !== "object") profile.loadout = {};
  if (!profile.holds[id]) profile.holds[id] = newHold();
  if (!(Number(profile.hp[id]) > 0)) profile.hp[id] = 1;
  if (!profile.loadout[id]) profile.loadout[id] = stockFor(id);
  return profile;
}

/**
 * Keep the old singular property as a non-enumerable compatibility view. Old
 * callers can still assign `profile.mission` or read its compact `{ type, p,
 * n, r, ... }` shape, while every saved active mission lives in `missions`.
 */
function legacyMissionView(mission) {
  if (!mission) return null;
  const step = mission.steps?.[mission.step < mission.steps.length ? mission.step : mission.steps.length - 1];
  const progress = mission.step >= mission.steps.length
    ? step?.count || mission.n || 0
    : mission.counters?.[step?.id || "objective"] ?? mission.p ?? 0;
  const out = {
    type: mission.type,
    tier: mission.tier || 1,
    p: Math.max(0, Math.floor(progress)),
    n: mission.n || step?.count || 1,
    r: mission.r ?? mission.rewards?.credits ?? 0,
  };
  if (mission.o !== undefined || step?.item !== undefined) out.o = mission.o ?? step.item;
  if (mission.e !== undefined || step?.enemy !== undefined) out.e = mission.e ?? step.enemy;
  return out;
}

function attachMissionCompat(profile) {
  Object.defineProperty(profile, "mission", {
    enumerable: false,
    configurable: true,
    get: () => profile.missions[0] ? legacyMissionView(profile.missions[0]) : null,
    set: value => {
      profile.missions = value ? [cleanMission(value)].filter(Boolean) : [];
    },
  });
  return profile;
}

/** Fresh portable character profile (travels with a pilot across worlds). */
export function newProfile() {
  return attachMissionCompat({
    v: SAVE_VERSION,
    cr: 600,
    holds: { [DEFAULT_SHIP]: newHold() },   // per ship: { itemId: count } in its hold
    ships: [DEFAULT_SHIP],
    ship: DEFAULT_SHIP,
    missions: [],       // active mission records; several may run at once
    flags: {},          // remembered story facts (used by later mission slices)
    done: 0,            // contracts completed
    kills: 0,
    msl: 0,             // missiles carried
    pw: "cannon",      // equipped primary
    hp: { [DEFAULT_SHIP]: 1 },   // hull fraction per owned ship (1 = intact)
    loadout: allStockFit(),      // fitted modules per hull, group -> bay array
  });
}

/** Fresh hosted world record (station levels and storage, contract board, galaxy and current pocket). */
export function newWorld() {
  return worldWithStationStores({
    v: SAVE_VERSION,
    base: { ...BASE_DEFAULT },
    board: [],       // the home station's contract offers (kept as the old field)
    boards: {},      // other stations' offers: place id -> compact offers
    galaxy: newGalaxyRecord(),
    place: DEFAULT_PLACE,
    destination: null, // local session destination, saved with this world
    resume: null,      // null = docked; { pos, quat, sh, en } = flying at that spot
    placeMemory: {},   // place id -> { rocks: { id: seconds }, encounters: { id: seconds } }
    missionState: {},  // story-script state keyed by place id
  }, { [HOME_STATION_KEY]: newStock() });
}

/** Compact map knowledge. No positions, pockets, links or generated content. */
export function newGalaxyRecord(seed = GALAXY.seed) {
  const home = PLACES[DEFAULT_PLACE].parent;
  return { seed: seed >>> 0, knowledge: { [home]: { discovered: true, visited: true } } };
}

function cleanGalaxyRecord(raw) {
  const seed = Number.isFinite(raw?.seed) ? raw.seed >>> 0 : GALAXY.seed;
  const knowledge = {};
  for (const [id, value] of Object.entries(raw?.knowledge || {})) {
    if (!isSystem(id) || !value || typeof value !== "object") continue;
    const visited = value.visited === true;
    const discovered = value.discovered === true || visited;
    if (discovered) knowledge[id] = { discovered: true, ...(visited ? { visited: true } : {}) };
  }
  const home = PLACES[DEFAULT_PLACE].parent;
  knowledge[home] = { discovered: true, visited: true };
  return { seed, knowledge };
}

/** Fresh combined save (`{ v, profile, world }`). */
export function newSave() {
  return {
    v: SAVE_VERSION,
    profile: newProfile(),
    world: newWorld(),
  };
}

/** Validate one compact contract offer in `world.board`. */
function cleanContract(raw) {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return null;
  if (!MISSION_TYPES.includes(raw.type)) return null;
  if (raw.o !== undefined && !isItem(raw.o)) return null;
  const n = Math.max(1, Math.floor(+raw.n || 1));
  const r = Math.max(0, Math.floor(+raw.r || 0));
  const tier = Math.max(1, Math.floor(+raw.tier || 1));
  const p = Math.max(0, Math.min(n, Math.floor(+raw.p || 0)));
  return { ...raw, tier, n, r, p };
}

const cleanFlags = raw => {
  const out = {};
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return out;
  for (const [id, value] of Object.entries(raw)) {
    if (!id || !/^[A-Za-z0-9_.:-]+$/.test(id)) continue;
    if (["boolean", "string", "number"].includes(typeof value) && (typeof value !== "number" || Number.isFinite(value))) {
      out[id] = value;
    }
  }
  return out;
};

function cleanMissionChoice(raw, index) {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return null;
  const id = typeof raw.id === "string" && raw.id ? raw.id : `choice-${index + 1}`;
  const text = typeof raw.text === "string" ? raw.text : id;
  const choice = { id, text };
  for (const key of ["next", "goto"]) if (raw[key] !== undefined) choice[key] = raw[key];
  const set = raw.set || raw.flags;
  if (set && typeof set === "object" && !Array.isArray(set)) choice.set = cleanFlags(set);
  return choice;
}

function cleanScriptAction(raw) {
  if (typeof raw === "string") return raw;
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return null;
  const action = {};
  for (const key of ["kind", "action", "type", "place", "sector", "feature", "anchor", "enemy", "ship", "item", "target", "sound", "name", "key", "value", "count", "to", "loot"]) {
    if (raw[key] !== undefined) action[key] = raw[key];
  }
  if (raw.dropOnDefeat && typeof raw.dropOnDefeat === "object" && !Array.isArray(raw.dropOnDefeat)) {
    action.dropOnDefeat = {
      item: raw.dropOnDefeat.item,
      count: raw.dropOnDefeat.count,
      scatter: raw.dropOnDefeat.scatter,
    };
  }
  if (Array.isArray(raw.spawnDist)) action.spawnDist = raw.spawnDist.slice(0, 2).map(Number);
  if (raw.set && typeof raw.set === "object" && !Array.isArray(raw.set)) action.set = cleanFlags(raw.set);
  if (raw.state && typeof raw.state === "object" && !Array.isArray(raw.state)) action.state = cleanFlags(raw.state);
  if (raw.args && typeof raw.args === "object" && !Array.isArray(raw.args)) action.args = { ...raw.args };
  return action;
}

function cleanMissionStep(raw, index) {
  if (!raw || typeof raw !== "object" || Array.isArray(raw) || !isMissionStepKind(raw.kind)) return null;
  const id = typeof raw.id === "string" && raw.id ? raw.id : `step-${index + 1}`;
  const step = { id, kind: raw.kind };
  for (const key of ["item", "enemy", "faction", "place", "sector", "target", "trigger", "speaker", "portrait", "log", "objective", "pause", "requiresDock", "requiresFlying", "requiresPlace", "allowCombat", "missionItem", "owned", "next", "goto", "then", "else", "ifTrue", "ifFalse", "timer", "seconds"]) {
    if (raw[key] !== undefined) step[key] = raw[key];
  }
  if (raw.lines !== undefined) {
    const lines = Array.isArray(raw.lines) ? raw.lines : [raw.lines];
    step.lines = lines.filter(line => typeof line === "string").map(String);
  }
  if (Array.isArray(raw.choices)) step.choices = raw.choices.map(cleanMissionChoice).filter(Boolean);
  if (raw.action !== undefined) {
    const actions = Array.isArray(raw.action) ? raw.action : [raw.action];
    step.action = actions.map(cleanScriptAction).filter(Boolean);
  }
  if (Array.isArray(raw.actions)) step.actions = raw.actions.map(cleanScriptAction).filter(Boolean);
  if (raw.set && typeof raw.set === "object" && !Array.isArray(raw.set)) step.set = cleanFlags(raw.set);
  if (raw.test !== undefined) step.test = raw.test;
  if (Array.isArray(raw.steps)) step.steps = raw.steps.map(cleanMissionStep).filter(Boolean);
  const count = Number(raw.count ?? raw.seconds ?? (step.kind === "dialogue" ? step.lines?.length : 1));
  step.count = Number.isFinite(count) && count > 0 ? count : 1;
  return step;
}

function restoreAuthoredStepMetadata(step, saved, authored) {
  if (!step || !authored) return;
  for (const key of ["requiresDock", "requiresFlying", "requiresPlace", "place"]) {
    if (saved?.[key] === undefined && authored?.[key] !== undefined) step[key] = authored[key];
  }
  for (const child of step.steps || []) {
    const savedChild = (saved?.steps || []).find(item => item?.id === child.id);
    const authoredChild = (authored?.steps || []).find(item => item?.id === child.id);
    restoreAuthoredStepMetadata(child, savedChild, authoredChild);
  }
}

function cleanMission(raw) {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return null;
  // v18 and older stored a compact contract directly in `profile.mission`.
  if (!raw.kind && MISSION_TYPES.includes(raw.type)) {
    return missionFromContract({ ...raw }, raw.id || `contract:${raw.type}:legacy`);
  }
  if (!isMissionKind(raw.kind) || !Array.isArray(raw.steps)) return null;
  let steps = raw.steps.map(cleanMissionStep).filter(Boolean);
  if (!steps.length) return null;
  const definition = STORY_MISSIONS.find(item => item.id === raw.id);
  const rawStep = Math.max(0, Math.floor(+raw.step || +raw.current || 0));
  const savedStepId = rawStep < steps.length ? steps[rawStep]?.id : null;
  const savedComplete = raw.completed === true || rawStep >= steps.length;
  let currentStep = rawStep;
  // Border Signal changed its authored order in v19 without changing the save
  // version. Rebuild that authored story's step array by stable step id so an
  // older v19 save cannot retain the old timeout/leave failure or run a
  // dialogue-to-spawn shortcut. Do this even when the step count happens to
  // match: authored order is not save state. Counters remain keyed by stable
  // ids below.
  if (definition?.id === "story.border-signal") {
    steps = definition.steps.map(cleanMissionStep).filter(Boolean);
    currentStep = savedComplete ? steps.length : Math.max(0, steps.findIndex(step => step.id === savedStepId));
  }
  // Older saves contain authored story steps but not newer presentation or
  // situation metadata. Restore that data-only metadata by step id without
  // changing dialogue progress or any mission state.
  if (definition) {
    for (const step of steps) {
      const saved = raw.steps.find(item => item?.id === step.id);
      const authored = definition.steps.find(item => item.id === step.id);
      restoreAuthoredStepMetadata(step, saved, authored);
    }
  }
  // Salvage contracts from the first 13a build counted any pickup. Keep their
  // progress, but make the required hand-in item explicit when they are saved again.
  if (raw.type === "salvage") {
    const collect = steps.find(step => step.kind === "collect");
    if (collect && !collect.item) collect.item = "salv";
    // Recovery contracts own the crates they put in space, so their count only
    // moves for their own crates. Saves written before that rule counted any
    // pickup; they keep the count they earned and gain the rule from here on.
    if (collect) collect.owned = true;
  }
  const step = Math.max(0, Math.min(steps.length, currentStep));
  const counters = {};
  const source = raw.counters && typeof raw.counters === "object" ? raw.counters : {};
  for (const item of steps) {
    if (item.kind === "parallel") {
      for (const child of item.steps || []) {
        const id = `${item.id}.${child.id}`;
        const value = Number(source[id]);
        counters[id] = Number.isFinite(value) && value >= 0 ? Math.min(child.count, value) : 0;
      }
      continue;
    }
    const value = Number(source[item.id]);
    counters[item.id] = Number.isFinite(value) && value >= 0 ? Math.min(item.count, value) : 0;
  }
  // Contract records generated by the data factory retain their compact fields;
  // use them to seed a v18 mission that did not yet have counters.
  if (raw.type && MISSION_TYPES.includes(raw.type) && raw.p !== undefined && counters[steps[0].id] === 0) {
    counters[steps[0].id] = Math.min(steps[0].count, Math.max(0, Math.floor(+raw.p || 0)));
  }
  const current = step >= steps.length ? steps.length : step;
  const rewards = raw.rewards && typeof raw.rewards === "object" ? {
    credits: Math.max(0, Math.floor(+raw.rewards.credits || 0)),
  } : { credits: Math.max(0, Math.floor(+raw.r || 0)) };
  const borderDefinition = definition?.id === "story.border-signal" ? definition : null;
  const authoredFails = borderDefinition?.fails
    ? { ...borderDefinition.fails, on: Array.isArray(borderDefinition.fails.on) ? [...borderDefinition.fails.on] : borderDefinition.fails.on }
    : null;
  const mission = {
    id: typeof raw.id === "string" && raw.id ? raw.id : `mission:${raw.type || "unknown"}`,
    title: typeof raw.title === "string" && raw.title ? raw.title : String(raw.type || "Mission"),
    kind: raw.kind,
    requires: Array.isArray(raw.requires) ? raw.requires.filter(id => typeof id === "string") : [],
    steps,
    rewards,
    fails: authoredFails || (raw.fails && typeof raw.fails === "object" ? { ...raw.fails } : {}),
    step: current,
    current,
    counters,
  };
  for (const key of ["type", "tier", "n", "r", "o", "e", "faction", "origin", "sector", "timeout", "elapsed", "failed", "failure", "failureMessage"]) {
    if (raw[key] !== undefined && !(borderDefinition && key === "timeout")) mission[key] = raw[key];
  }
  // `handIn` is part of the mission: the sentence shown while the cargo is owed
  // and, for a mission handed in somewhere specific, the station that takes it.
  // Additive field (v19): an older record without it resolves the station from
  // `origin`, so no save migration is needed.
  if (raw.handIn && typeof raw.handIn === "object" && !Array.isArray(raw.handIn)) {
    const handIn = {};
    if (typeof raw.handIn.objective === "string" && raw.handIn.objective) handIn.objective = raw.handIn.objective;
    if (typeof raw.handIn.station === "string" && raw.handIn.station) handIn.station = raw.handIn.station;
    if (Object.keys(handIn).length) mission.handIn = handIn;
  }
  if (borderDefinition) {
    mission.origin = borderDefinition.origin;
    delete mission.timeout;
    // The authored story hand-in station wins over whatever a save carried.
    if (borderDefinition.handIn?.station) mission.handIn = { ...(mission.handIn || {}), station: borderDefinition.handIn.station };
  }
  if (mission.type && MISSION_TYPES.includes(mission.type)) {
    mission.tier = Math.max(1, Math.floor(+mission.tier || 1));
    mission.n = Math.max(1, Math.floor(+mission.n || steps[0].count));
    mission.r = Math.max(0, Math.floor(Number.isFinite(+mission.r) ? +mission.r : rewards.credits));
  }
  mission.p = Math.floor(counters[steps[Math.min(current, steps.length - 1)].id] || 0);
  return mission;
}

/**
 * Validate and upgrade a character `profile` (either a standalone v13 profile
 * or a legacy v1..v12 flat save). World fields (`base`, `store`, `board`,
 * `galaxy`, `place`) are excluded here and handled by `sanitizeWorld`.
 */
export function sanitizeProfile(raw) {
  if (!raw || typeof raw !== "object" || !Array.isArray(raw.ships)) {
    throw new Error("not a Tallow Reach save");
  }
  const rawVersion = +raw.v || 1;
  const oldShape = rawVersion < 12;

  const cr = Math.max(0, Math.floor(+raw.cr || 0));
  let ships = [...new Set(raw.ships.filter(id => SHIPS[id]))];
  let ship = ships.includes(raw.ship) ? raw.ship : ships[0] || DEFAULT_SHIP;

  // Lost every ship and cannot afford another: the station lends a Wasp.
  if (!ships.length && cr < SHIPS.wasp.price) {
    ships = [DEFAULT_SHIP];
    ship = DEFAULT_SHIP;
  }

  const msl = Math.max(0, Math.min(MODULES.missile_basic.cap, Math.floor(+raw.msl || 0)));
  const pw = raw.pw === "beam" ? "beam" : "cannon";

  const hp = {};
  const rawHp = raw.hp && typeof raw.hp === "object" ? raw.hp : {};
  for (const id of ships) {
    const v = +rawHp[id];
    hp[id] = v > 0 && v <= 1 ? v : 1;
  }

  const loadout = cleanLoadouts(raw.loadout, rawVersion);

  // v11: every ship has its own hold. A save from before that carried one `cargo`
  // object for the ship being flown, so that ship gets it.
  const oldCargo = raw.holds ? null : raw.cargo;
  const holds = cleanHolds(raw.holds, ships, oldShape);
  if (oldCargo && holds[ship]) mergeStock(holds[ship], cleanStock(oldCargo));

  const done = Math.max(0, Math.floor(+raw.done || 0));
  const kills = Math.max(0, Math.floor(+raw.kills || 0));
  const rawMissions = Array.isArray(raw.missions)
    ? raw.missions
    : raw.mission
      ? [raw.mission]
      : [];
  const missions = rawMissions.map(cleanMission).filter(Boolean);

  return attachMissionCompat({
    v: SAVE_VERSION,
    cr,
    holds,
    ships,
    ship,
    missions,
    flags: cleanFlags(raw.flags),
    done,
    kills,
    msl,
    pw,
    hp,
    loadout,
  });
}

/**
 * Validate a saved resume point. Returns null (meaning "docked, or no spot
 * saved") for anything missing, non-finite, the wrong shape, or implausibly far
 * from the pocket origin — a damaged or hand-edited save must never place the
 * ship somewhere it cannot fly back from.
 */
function cleanResume(raw) {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return null;
  const vec = (a, n) =>
    Array.isArray(a) && a.length === n && a.every(v => typeof v === "number" && Number.isFinite(v))
      ? a.slice()
      : null;
  const pos = vec(raw.pos, 3);
  if (!pos || pos.some(v => Math.abs(v) > PLACE_EXTENT)) return null;
  let quat = vec(raw.quat, 4);
  if (quat) {
    const len = Math.hypot(...quat);
    if (len <= 1e-6) quat = [0, 0, 0, 1];
    else if (Math.abs(len - 1) > 1e-6) quat = quat.map(v => v / len);
  }
  const num = v => (typeof v === "number" && Number.isFinite(v) && v >= 0 ? v : null);
  return { pos, quat: quat || [0, 0, 0, 1], sh: num(raw.sh), en: num(raw.en) };
}

/** Validate a destination against the currently installed seeded galaxy. */
function cleanDestination(raw) {
  if (typeof raw === "string") return isSystem(raw) ? raw : null;
  if (raw && typeof raw === "object" && !Array.isArray(raw) && typeof raw.pocketId === "string" && isPocket(raw.pocketId)) {
    return { pocketId: raw.pocketId };
  }
  return null;
}

/**
 * Keep only positive, finite remaining simulation seconds. Place ids are left
 * intact even when a removed/generated pocket is not in the current catalog;
 * the next world load can decide whether that pocket still exists.
 */
function cleanPlaceMemory(raw) {
  const out = {};
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return out;
  const max = 7 * 24 * 60 * 60;
  for (const [placeId, record] of Object.entries(raw)) {
    if (!placeId || !record || typeof record !== "object" || Array.isArray(record)) continue;
    const clean = { rocks: {}, encounters: {} };
    for (const bucket of ["rocks", "encounters"]) {
      const source = record[bucket];
      if (!source || typeof source !== "object" || Array.isArray(source)) continue;
      for (const [id, value] of Object.entries(source)) {
        const seconds = Number(value);
        if (id && Number.isFinite(seconds) && seconds > 0) clean[bucket][id] = Math.min(max, seconds);
      }
    }
    if (Object.keys(clean.rocks).length || Object.keys(clean.encounters).length) out[placeId] = clean;
  }
  return out;
}

/** A mission crate is the one entity that belongs in the saved world half:
 * its place, item and defeat position are enough to rebuild the visible crate;
 * the runtime id, quaternion and timer are session details. */
function cleanMissionDrop(raw) {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return null;
  const missionId = typeof raw.missionId === "string" && raw.missionId ? raw.missionId : null;
  // Before the physical-drop follow-up, Border Signal called its authored
  // object `salv`. Ordinary salvage keeps that id; only the authored record is
  // migrated to the now-catalogued Beacon.
  const savedItem = raw.missionId === "story.border-signal" && raw.item === "salv" ? "beacon" : raw.item;
  const item = typeof savedItem === "string" && isItem(savedItem) ? savedItem : null;
  const pos = Array.isArray(raw.pos) && raw.pos.length === 3 && raw.pos.every(value =>
    typeof value === "number" && Number.isFinite(value) && Math.abs(value) <= PLACE_EXTENT
  ) ? raw.pos.slice() : null;
  if (!missionId || !item || !pos) return null;
  // A recovery contract puts several crates of one item in space, one record per
  // crate, told apart by `slot`. Older records have none and stay slot-less.
  const slot = Number.isInteger(raw.slot) && raw.slot >= 0 ? raw.slot : null;
  return slot == null
    ? { missionId, item, pos, collected: raw.collected === true }
    : { missionId, item, slot, pos, collected: raw.collected === true };
}

/** Clean small, data-only state written by story scripts for each place. */
function cleanMissionState(raw) {
  const out = {};
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return out;
  for (const [place, values] of Object.entries(raw)) {
    if (!place || !values || typeof values !== "object" || Array.isArray(values)) continue;
    const clean = {};
    for (const [key, value] of Object.entries(values)) {
      if (key === "drops") {
        if (!Array.isArray(value)) continue;
        const drops = [];
        for (const rawDrop of value) {
          const drop = cleanMissionDrop(rawDrop);
          if (!drop || drops.some(existing =>
            existing.missionId === drop.missionId && existing.item === drop.item &&
            (existing.slot ?? null) === (drop.slot ?? null))) continue;
          drops.push(drop);
        }
        if (drops.length) clean.drops = drops;
        continue;
      }
      if (!key || !["boolean", "string", "number"].includes(typeof value)) continue;
      if (typeof value !== "number" || Number.isFinite(value)) clean[key] = value;
    }
    if (Object.keys(clean).length) out[place] = clean;
  }
  return out;
}

/** Clean each station's independent stock. Unknown station keys are retained
 * as namespaced save records so a catalog can be regenerated before use. */
function cleanStationStores(raw) {
  const out = {};
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return out;
  for (const [station, stock] of Object.entries(raw)) {
    if (!station || !stock || typeof stock !== "object" || Array.isArray(stock)) continue;
    const clean = cleanStock(stock);
    if (Object.keys(clean).length) out[station] = clean;
  }
  return out;
}

/**
 * Validate and upgrade a `world` record (either a v13 world object or the
 * world-owned fields of a legacy v1..v12 flat save). Base modules are walked
 * from `BASE_MODULES` rather than named by hand.
 */
export function sanitizeWorld(raw) {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
    throw new Error("not a Tallow Reach save");
  }
  const isLegacyFlat = Array.isArray(raw.ships);
  const rawVersion = typeof raw.v === "number" ? raw.v : isLegacyFlat ? 1 : SAVE_VERSION;
  const oldShape = rawVersion < 12;

  const rb = raw.base && typeof raw.base === "object" ? raw.base : {};
  const base = {};
  for (const [id, m] of Object.entries(BASE_MODULES)) {
    const lo = BASE_DEFAULT[id] ?? 0;
    base[id] = clampLevel(rb[id], lo, m.max);
  }

  // Station storage (`store` since v1; loose `modules` list poured in for < v12;
  // unlocked `wp.beam` / `wp.msl` granted as a stored module for < v8 / < v9).
  // Before station-local storage every station shared `store`. A pre-extension
  // save has no `stationStores`, so migrate that stock to the station at the
  // saved pocket when it has one; this preserves a save made at a generated
  // trader instead of silently moving its stock to Meridian.
  let store = cleanStock(raw.store);
  let stationStores = cleanStationStores(raw.stationStores);
  const hasStationStores = !!raw.stationStores && typeof raw.stationStores === "object" && !Array.isArray(raw.stationStores);
  const homeStation = HOME_STATION_KEY;
  const savedPlace = typeof raw.place === "string" && isPocket(raw.place)
    ? raw.place
    : typeof raw.sector === "string" && isPocket(raw.sector)
      ? raw.sector
      : DEFAULT_PLACE;
  const localStation = stationKeyAt(savedPlace);
  // Before gate/station separation, a generated trader could live directly on
  // a gate pocket. A docked save at that old pocket now resumes in the newly
  // generated station pocket, and any already-keyed stock follows the same
  // station feature onto its new pocket. Flying saves keep their exact gate
  // location and are not silently moved.
  const detachedPlace = `${savedPlace}-station`;
  const detachedStation = !localStation && isPocket(detachedPlace) ? stationKeyAt(detachedPlace) : null;
  const relocateDockedStation = !!detachedStation && raw.resume == null;
  const savedStation = localStation || detachedStation || homeStation;
  if (oldShape) for (const id of cleanModuleList(raw.modules)) addToStock(store, id, 1);
  const hadOldBeam = !!((raw.wp || {}).beam);
  const hadOldLauncher = !!((raw.wp || {}).msl);
  if (rawVersion < 8 && hadOldBeam && !store.beam_basic) addToStock(store, "beam_basic", 1);
  if (rawVersion < 9 && hadOldLauncher && !store.missile_basic) addToStock(store, "missile_basic", 1);

  if (detachedStation && hasStationStores) {
    const oldPrefix = `${savedPlace}:`;
    for (const [key, stock] of Object.entries(stationStores)) {
      if (!key.startsWith(oldPrefix)) continue;
      stationStores[detachedStation] = mergeStock(stationStores[detachedStation] || newStock(), stock);
      delete stationStores[key];
    }
  }

  if (!hasStationStores && savedStation !== homeStation) {
    // A legacy world.store represented the station where the save was made.
    stationStores[savedStation] = store;
    store = newStock();
  }
  // `world.store` is an old compatibility alias. If a save contains both forms,
  // keep the union in the canonical home key rather than duplicating stock.
  const homeStore = stationStores[homeStation] || newStock();
  for (const [id, count] of Object.entries(store)) {
    homeStore[id] = Math.max(homeStore[id] || 0, count);
  }
  stationStores[homeStation] = homeStore;

  const board = Array.isArray(raw.board) ? raw.board.map(cleanContract).filter(Boolean) : [];
  // Per-station boards are additive (v19): the home station keeps using `board`,
  // every other station has its own list here, generated when it is first read.
  const boards = {};
  if (raw.boards && typeof raw.boards === "object" && !Array.isArray(raw.boards)) {
    for (const [placeId, offers] of Object.entries(raw.boards)) {
      if (!isPocket(placeId) || placeId === DEFAULT_PLACE) continue;   // home is `board`
      const clean = Array.isArray(offers) ? offers.map(cleanContract).filter(Boolean) : [];
      if (clean.length) boards[placeId] = clean;
    }
  }
  // v15 and older had galaxy:null. Never trust/save generated geography here;
  // galaxy-session installs the seed's catalog before this validation runs.
  const galaxy = cleanGalaxyRecord(raw.galaxy);
  // v14: current pocket. v13 and older saves stored the same ids as `sector`.
  const place = relocateDockedStation ? detachedPlace
    : typeof raw.place === "string" && isPocket(raw.place)
      ? raw.place
      : typeof raw.sector === "string" && isPocket(raw.sector)
        ? raw.sector
        : DEFAULT_PLACE;

  return worldWithStationStores({
    v: SAVE_VERSION,
    base,
    board,
    boards,
    galaxy,
    place,
    destination: cleanDestination(raw.destination),
    resume: cleanResume(raw.resume),
    placeMemory: cleanPlaceMemory(raw.placeMemory),
    missionState: cleanMissionState(raw.missionState),
  }, stationStores);
}

/**
 * Validate and upgrade a complete save. Accepts both the v13 split shape
 * `{ v: 13, profile, world }` and any legacy v1..v12 flat save object.
 */
export function sanitizeSave(raw) {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
    throw new Error("not a Tallow Reach save");
  }
  if (raw.profile && typeof raw.profile === "object") {
    return {
      v: SAVE_VERSION,
      profile: sanitizeProfile(raw.profile),
      world: sanitizeWorld(raw.world && typeof raw.world === "object" ? raw.world : {}),
    };
  }
  if (Array.isArray(raw.ships)) {
    return {
      v: SAVE_VERSION,
      profile: sanitizeProfile(raw),
      world: sanitizeWorld(raw),
    };
  }
  throw new Error("not a Tallow Reach save");
}

/**
 * Extract a deep-cloned portable `profile` from `save` — the half a guest
 * carries into someone else's hosted world (credits, ships, loadouts, holds,
 * hull damage, missiles, active mission and stats, with zero station/world data).
 */
export function portableProfile(save) {
  const clean = sanitizeSave(save);
  return sanitizeProfile(JSON.parse(JSON.stringify(clean.profile)));
}

/**
 * Return a new save that merges an updated portable `profile` back into `save`
 * while keeping `save`'s own `world` (station levels, station storage, board,
 * galaxy, current pocket and resume point) untouched. Pure: neither input is mutated.
 */
export function mergeProfile(save, profile) {
  const cleanSave = sanitizeSave(save);
  const cleanProfile = sanitizeProfile(JSON.parse(JSON.stringify(profile)));
  const cleanWorld = sanitizeWorld(JSON.parse(JSON.stringify(cleanSave.world)));
  return {
    v: SAVE_VERSION,
    profile: cleanProfile,
    world: cleanWorld,
  };
}

/**
 * A stock — `{ itemId: count }` — as a save keeps it: known items only, whole
 * counts, and no entry for something that is not there.
 */
function cleanStock(src) {
  const out = newStock();
  if (!src || typeof src !== "object" || Array.isArray(src)) return out;
  for (const [id, n] of Object.entries(src)) {
    const count = Math.floor(+n || 0);
    if (isItem(id) && count > 0) out[id] = count;
  }
  return out;
}

/** Add `n` of `id` to a stock, whatever the room: a save is not a purchase. */
function addToStock(stock, id, n = 1) {
  if (!isItem(id) || !(n > 0)) return stock;
  stock[id] = (stock[id] || 0) + n;
  return stock;
}

/** Add every count of `src` to `stock`. */
function mergeStock(stock, src) {
  for (const [id, n] of Object.entries(src || {})) addToStock(stock, id, n);
  return stock;
}

/** An old `modules` list: real module ids only, in the order they were stored. */
function cleanModuleList(raw) {
  return Array.isArray(raw) ? raw.filter(id => isModule(id)) : [];
}

/**
 * One hold per owned ship. Before version 12 a hold was `{ cargo, modules }`
 * (goods and a list of parts); both are poured into the one stock now.
 */
function cleanHolds(raw, ships, oldShape) {
  const out = {};
  for (const id of ships) {
    const h = raw && typeof raw === "object" ? raw[id] : null;
    const stock = cleanStock(oldShape && h ? h.cargo : h);
    if (oldShape && h) for (const m of cleanModuleList(h.modules)) addToStock(stock, m, 1);
    out[id] = stock;
  }
  return out;
}

function clampLevel(value, lo, hi) {
  const n = value === undefined || value === null ? lo : Math.floor(+value || 0);
  return Math.min(hi, Math.max(lo, n));
}

/**
 * Rebuild every hull's loadout from a save. Unknown modules are dropped, a bay
 * beyond the hull's layout is dropped, and a hull with no saved loadout (an old
 * save, or a hull added in an update) gets the stock fit. A bay the player has
 * really left empty stays empty: only a missing hull or group falls back.
 */
function cleanLoadouts(saved, version) {
  const addedLater = [];
  if (version < 5) addedLater.push("thruster");
  if (version < 6) addedLater.push("shield");
  if (version < 7) addedLater.push("primary");
  if (version < 10) addedLater.push("hull");
  const out = {};
  for (const id of Object.keys(SHIPS)) {
    const layout = layoutFor(id),
      stock = stockFor(id),
      forShip = saved && saved[id];
    const fit = {};
    for (const [g, slots] of Object.entries(layout)) {
      const src =
        addedLater.includes(g) || !forShip || !Array.isArray(forShip[g]) ? stock[g] : forShip[g];
      fit[g] = Array.from({ length: slots }, (_, i) => {
        const m = src[i];
        return MODULES[m] && MODULES[m].g === g ? m : null;
      });
    }
    out[id] = fit;
  }
  return out;
}
